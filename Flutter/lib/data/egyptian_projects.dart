  /// Get all project names for dropdown
  static List<String> get allProjectNames {
    return allProjects.map((project) => project['name']!).toList()..sort();
  }

  /// Get projects by location
  static List<Map<String, String>> getProjectsByLocation(String location) {
    return allProjects
        .where(
          (project) => project['location']!.toLowerCase().contains(
            location.toLowerCase(),
          ),
        )
        .toList();
  }

  /// Get projects by developer
  static List<Map<String, String>> getProjectsByDeveloper(String developer) {
    return allProjects
        .where(
          (project) => project['developer']!.toLowerCase().contains(
            developer.toLowerCase(),
          ),
        )
        .toList();
  }

  /// Get projects by type
  static List<Map<String, String>> getProjectsByType(String type) {
    return allProjects
        .where(
          (project) =>
              project['type']!.toLowerCase().contains(type.toLowerCase()),
        )
        .toList();
  }

  /// Search projects by name
  static List<Map<String, String>> searchProjects(String query) {
    if (query.isEmpty) return allProjects;

    return allProjects
        .where(
          (project) =>
              project['name']!.toLowerCase().contains(query.toLowerCase()) ||
              project['developer']!.toLowerCase().contains(
                query.toLowerCase(),
              ) ||
              project['location']!.toLowerCase().contains(query.toLowerCase()),
        )
        .toList();
  }

  /// Get unique locations
  static List<String> get allLocations {
    return allProjects.map((project) => project['location']!).toSet().toList()
      ..sort();
  }

  /// Get unique developers
  static List<String> get allDevelopers {
    return allProjects.map((project) => project['developer']!).toSet().toList()
      ..sort();
  }

  /// Get unique types
  static List<String> get allTypes {
    return allProjects.map((project) => project['type']!).toSet().toList()
      ..sort();
  }
