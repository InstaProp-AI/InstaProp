// Country data for project selection
export interface Country {
  code: string;
  name: string;
  flag: string;
}

// Get flag emoji from ISO country code
export const getCountryFlag = (countryCode: string): string => {
  if (!countryCode || countryCode.length !== 2) return '🌍';
  
  // Convert country code to flag emoji
  const code = countryCode.toUpperCase();
  let flag = '';
  for (let i = 0; i < code.length; i++) {
    const codePoint = code.charCodeAt(i);
    if (codePoint >= 65 && codePoint <= 90) {
      // Regional Indicator Symbol Letter A starts at 0x1F1E6
      flag += String.fromCodePoint(0x1F1E6 + (codePoint - 65));
    }
  }
  return flag;
};

